#!/usr/bin/env bash

fail() {
    printf 'Ошибка: %s\n' "$*" >&2
    exit 1
}

validate_parameters() {
    [[ $# -eq 6 ]] || fail 'Ожидается ровно 6 аргументов. Пример: ./main.sh /opt/test 4 az 5 az.az 3kb'

    [[ $1 == /* ]] || fail 'Первый аргумент должен быть абсолютным путём.'
    [[ -d $1 || ! -e $1 && ! -L $1 ]] || fail 'Указанный путь существует и не является каталогом.'

    [[ $2 =~ ^[1-9][0-9]*$ && ${#2} -le 18 ]] || fail 'Количество папок должно быть положительным целым числом.'
    [[ $3 =~ ^[a-zA-Z]{1,7}$ ]] || fail 'Буквы папок: от 1 до 7 английских букв без цифр и других символов.'
    [[ $4 =~ ^[1-9][0-9]*$ && ${#4} -le 18 ]] || fail 'Количество файлов должно быть положительным целым числом.'

    if [[ $5 =~ ^([a-zA-Z]{1,7})\.([a-zA-Z]{1,3})$ ]]; then
        FILE_LETTERS="${BASH_REMATCH[1]}"
        FILE_EXTENSION="${BASH_REMATCH[2]}"
    else
        fail 'Пятый аргумент должен иметь вид name.ext (name: 1–7 букв, ext: 1–3 буквы).'
    fi

    if [[ $6 =~ ^(100|[1-9][0-9]?)[kK][bB]$ ]]; then
        FILE_SIZE_KB="${BASH_REMATCH[1]}"
    else
        fail 'Размер файла должен быть от 1kb до 100kb включительно.'
    fi

    FOLDER_COUNT="$2"
    FOLDER_LETTERS="$3"
    FILE_COUNT="$4"
}
